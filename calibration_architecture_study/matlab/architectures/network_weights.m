% ============================================================================
% network_weights.m —— 解节点电荷方程，求每个电容的“有效权重”
% ----------------------------------------------------------------------------
% 角色：把分段电容网络建模为线性节点电容矩阵 C，解 C·g = e_TOP，得到各节点对
%       顶端(TOP)节点的归一化耦合系数 g；再由“电容×其节点系数”得到每个电容的
%       有效权重 w（桥电容会引入非对角耦合，使权重不再等于标称二进制权重）。
% 输入  ：a —— 架构结构体；cap —— 各节点实际电容(单位 Cu，含失配)；
%        bridge —— 桥电容数组
% 输出  ：w —— 每个电容的有效权重向量；g —— 节点耦合系数；C —— 节点电容矩阵
% 关键算法：对称矩阵 C 求逆的第一行 = g，利用对称性避免显式求逆（只解一个右端向量）。
% ============================================================================
function [w,g,C] = network_weights(a,cap,bridge)
% Values in Cu. Solve C*g=e_TOP; symmetry gives first row of C^-1.
nnode=max(a.seg); totals=accumarray(a.seg(:),cap(:),[nnode 1]);  % 按分段 seg 聚合出每段总电容
C=diag(totals);  % 初始化节点电容矩阵 C 为对角阵（各段自电容）
for j=1:numel(bridge)
    v=zeros(nnode,1); v(j)=1; v(j+1)=-1;  % 桥电容连接第 j 与 j+1 段，方向从 j 指向 j+1
    C=C+bridge(j)*(v*v');  % 用外积把桥电容的非对角耦合加到 C 上（对称秩-1 更新）
end
e=zeros(nnode,1); e(1)=1; g=C\e;  % 右端向量只在 TOP 节点(段1)置 1；解线性系统得到各节点耦合系数 g
w=reshape(cap,1,[]).*reshape(g(a.seg),1,[]);  % 每个电容权重 = 其电容值 × 所属段的耦合系数 g(seg)，得到有效权重 w
end
